// Generates a deterministic, valid signed-transfer test vector for the C++
// transaction-validation tests (cpp/src/main.cpp, testTxValidation). The C++
// side has Ed25519 *verification* only, so a known-good signature must be
// produced here with the same wallet/serialization the real frontend uses.
//
// Run from the frontend/ directory (it has the @noble deps):
//   node scripts/gen-validation-vector.mjs
//
// The output block is pasted verbatim into the C++ test. The test recomputes
// both txIds and asserts they equal these constants, so any serialization drift
// fails loudly rather than silently passing.

import * as ed from '@noble/ed25519';
import { sha256 } from '@noble/hashes/sha256';
import { sha512 } from '@noble/hashes/sha512';
import { bytesToHex, hexToBytes, utf8ToBytes } from '@noble/hashes/utils';

ed.etc.sha512Sync = (...m) => sha512(ed.etc.concatBytes(...m));

// ─── Serialization (byte-for-byte identical to Transaction.cpp / Hash.cpp) ───
const concat = (parts) => {
  const total = parts.reduce((n, p) => n + p.length, 0);
  const out = new Uint8Array(total);
  let off = 0;
  for (const p of parts) { out.set(p, off); off += p.length; }
  return out;
};
const uint16BE = (n) => new Uint8Array([(n >> 8) & 0xff, n & 0xff]);
const serializeString = (s) => concat([uint16BE(utf8ToBytes(s).length), utf8ToBytes(s)]);
const serializeAmount = (amount) => {
  let units = BigInt(Math.round(amount * 1e8));
  const buf = new Uint8Array(8);
  for (let i = 7; i >= 0; i--) { buf[i] = Number(units & 0xffn); units >>= 8n; }
  return buf;
};

// coinbase txId = SHA256("coinbase" | proofId | count | [addr,amount,reason]…)
function coinbaseTxId(proofId, outputs) {
  const parts = [serializeString('coinbase'), serializeString(proofId), uint16BE(outputs.length)];
  for (const o of outputs) {
    parts.push(serializeString(o.address), serializeAmount(o.amount), serializeString(o.reason));
  }
  return bytesToHex(sha256(concat(parts)));
}

// transfer txId = SHA256("transfer" | inCount | [prevId,idx]… | outCount | [addr,amount]…)
function transferTxId(inputs, outputs) {
  const parts = [serializeString('transfer'), uint16BE(inputs.length)];
  for (const i of inputs) { parts.push(serializeString(i.prev_tx_id), uint16BE(i.output_index)); }
  parts.push(uint16BE(outputs.length));
  for (const o of outputs) { parts.push(serializeString(o.address), serializeAmount(o.amount)); }
  return bytesToHex(sha256(concat(parts)));
}

// ─── Fixed wallet (deterministic) ────────────────────────────────────────────
const privHex = 'c5aa8df43f9f837bedb7442f31dcb7b166d38535076f094b85ce3a2e0b4458f7';
const pub = ed.getPublicKey(hexToBytes(privHex));
const publicKey = bytesToHex(pub);
const address = bytesToHex(sha256(pub));   // hex(SHA256(publicKey)) — platform address

// ─── Coinbase that funds the wallet, then a transfer that spends it ───────────
const AMOUNT = 5;
const proofId = 'test-proof-vector';
const cbId = coinbaseTxId(proofId, [{ address, amount: AMOUNT, reason: 'bug_bounty' }]);

const inputs = [{ prev_tx_id: cbId, output_index: 0 }];
const outputs = [{ address, amount: AMOUNT }];     // send back to self → conservation holds
const txId = transferTxId(inputs, outputs);
const signature = bytesToHex(ed.sign(hexToBytes(txId), hexToBytes(privHex)));

console.log(`// Generated by frontend/scripts/gen-validation-vector.mjs — do not edit by hand.
static const char* VEC_PRIVATE_KEY = "${privHex}";
static const char* VEC_PUBLIC_KEY  = "${publicKey}";
static const char* VEC_ADDRESS     = "${address}";
static const char* VEC_PROOF_ID    = "${proofId}";
static constexpr double VEC_AMOUNT  = ${AMOUNT};
static const char* VEC_COINBASE_TXID = "${cbId}";
static const char* VEC_TRANSFER_TXID = "${txId}";
static const char* VEC_SIGNATURE   = "${signature}";`);
